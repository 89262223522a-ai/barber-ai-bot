const TelegramBot = require("node-telegram-bot-api");
const OpenAI = require("openai");

const telegramToken = process.env.TELEGRAM_BOT_TOKEN;
const openaiApiKey = process.env.OPENAI_API_KEY;

if (!telegramToken) {
  throw new Error("Не найдена переменная TELEGRAM_BOT_TOKEN");
}

if (!openaiApiKey) {
  throw new Error("Не найдена переменная OPENAI_API_KEY");
}

const bot = new TelegramBot(telegramToken, { polling: true });

const openai = new OpenAI({
  apiKey: openaiApiKey,
});

const systemPrompt = `
Ты — сильный русскоязычный ИИ-маркетолог и ассистент владельца барбершопа.

Твоя задача — помогать привлекать клиентов на мужские стрижки законными, этичными и практичными способами.

Ты умеешь:
— определять целевую аудиторию;
— создавать выгодные офферы и акции;
— писать рекламные объявления для Telegram, VK, Яндекс Директа, Яндекс Карт и 2ГИС;
— создавать посты и сценарии коротких видео;
— предлагать локальные каналы продвижения и партнёрства;
— делать планы продвижения на 7 или 30 дней;
— создавать вежливые скрипты для ответов клиентам и записи на услуги;
— анализировать результаты рекламы, если пользователь передал цифры.

Правила ответа:
1. Пиши по-русски, ясно, без сложных терминов.
2. Давай конкретные шаги, которые можно выполнить.
3. Если не хватает данных — сначала задай до 3 коротких уточняющих вопросов.
4. Не предлагай покупать базы номеров, собирать личные контакты людей без согласия, делать спам или нарушать правила рекламных площадок.
5. В конце крупных ответов добавляй блок «Что сделать сегодня» с 3 ближайшими действиями.
6. Если пользователь просит рекламный текст — предложи минимум 3 варианта.
`;

bot.onText(/\/start/, async (msg) => {
  const chatId = msg.chat.id;

  await bot.sendMessage(
    chatId,
    `Привет! Я ИИ-ассистент для продвижения барбершопа. 💈

Я помогу создать рекламу, офферы, посты, сценарии ответов клиентам и план привлечения записей.

Напишите задачу обычным сообщением. Например:

«Нужно больше клиентов на мужскую стрижку. Город Казань, район Центр. Бюджет 20 000 ₽. Первое посещение — скидка 15%.»

Или используйте команды:
/оффер — придумать акцию
/реклама — написать объявления
/пост — создать пост для соцсетей
/план — составить план продвижения`
  );
});

bot.onText(/\/оффер/, (msg) => {
  bot.sendMessage(
    msg.chat.id,
    "Напишите: город, район, среднюю цену стрижки, вашу акцию и кому хотите продавать услугу. Я подготовлю несколько сильных офферов."
  );
});

bot.onText(/\/реклама/, (msg) => {
  bot.sendMessage(
    msg.chat.id,
    "Напишите, где будет реклама (Telegram, VK, Яндекс), город/район, бюджет, услугу и акцию. Я создам варианты объявлений."
  );
});

bot.onText(/\/пост/, (msg) => {
  bot.sendMessage(
    msg.chat.id,
    "Напишите тему поста, город и цель: привлечь новых клиентов, вернуть старых или рассказать об акции."
  );
});

bot.onText(/\/план/, (msg) => {
  bot.sendMessage(
    msg.chat.id,
    "Напишите город, район, месячный рекламный бюджет, средний чек и сколько новых клиентов хотите получать. Я составлю план."
  );
});

bot.on("message", async (msg) => {
  const chatId = msg.chat.id;
  const text = msg.text;

  if (!text || text.startsWith("/")) {
    return;
  }

  try {
    await bot.sendChatAction(chatId, "typing");

    const response = await openai.responses.create({
      model: "gpt-4.1-mini",
      instructions: systemPrompt,
      input: text,
    });

    const answer =
      response.output_text ||
      "Не удалось сформировать ответ. Попробуйте написать запрос ещё раз.";

    // Telegram ограничивает длину одного сообщения.
    const parts = answer.match(/[\s\S]{1,4000}/g) || [];

    for (const part of parts) {
      await bot.sendMessage(chatId, part);
    }
  } catch (error) {
    console.error(error);

    await bot.sendMessage(
      chatId,
      "Произошла техническая ошибка. Проверьте, добавлены ли ключ OpenAI и токен Telegram в переменные окружения BotHost."
    );
  }
});

console.log("Бот запущен");
